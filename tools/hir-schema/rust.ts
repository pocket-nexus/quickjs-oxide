// ---- strip ----

function stripStmt(s: Schema, f: Field, e: string, seen: Set<string>): string[] {
  const t = f.type;
  if (f.typed) {
    if (t.t === "list") return [`${e}.clear();`];
    if (t.t === "nullable") return [`*${e} = None;`];
    if (t.t === "prim" && t.name === "boolean") return [`*${e} = false;`];
    if (t.t === "named" && decl(s, t.name).d === "ref") return [`*${e} = ${t.name}(0);`];
    throw new Error(`cannot strip ${f.name}`);
  }
  return visit(s, t, e, seen);
}

function needsVisit(s: Schema, t: TypeExpr, seen: Set<string> = new Set()): boolean {
  switch (t.t) {
    case "prim":
      return false;
    case "list":
      return needsVisit(s, t.elem, seen);
    case "nullable":
      return needsVisit(s, t.inner, seen);
    case "named": {
      const d = decl(s, t.name);
      if (d.d === "ref" || d.d === "enum") return false;
      if (seen.has(t.name)) return true;
      seen.add(t.name);
      const fields = d.d === "struct" ? d.fields : [...d.variants.flatMap((v) => v.fields), ...d.common];
      return fields.some((f) => f.typed || needsVisit(s, f.type, seen));
    }
  }
}

function visit(s: Schema, t: TypeExpr, e: string, seen: Set<string>): string[] {
  if (!needsVisit(s, t)) return [];
  switch (t.t) {
    case "list":
      return [`for x in ${e}.iter_mut() { ${visit(s, t.elem, "x", seen).join(" ")} }`];
    case "nullable":
      return [`if let Some(x) = ${e}.as_mut() { ${visit(s, t.inner, "x", seen).join(" ")} }`];
    case "named":
      return [`${fnName("s", t.name)}(${e});`];
  }
  return [];
}

function stripper(s: Schema, o: Out): void {
  o.line("// ---- strip ----");
  o.line();
  for (const name of s.order) {
    const d = decl(s, name);
    if (name === "Program" || (d.d !== "struct" && d.d !== "union")) continue;
    if (!needsVisit(s, { t: "named", name })) continue;
    const seen = new Set<string>();
    o.line(`fn ${fnName("s", name)}(v: &mut ${name}) {`);
    if (d.d === "struct") {
      for (const f of d.fields) for (const l of stripStmt(s, f, `(&mut v.${rustField(f.name)})`, seen)) o.line("    " + l);
    } else {
      const k = kindEnum(d);
      o.line(`    match ${d.common.length ? "&mut v.kind" : "v"} {`);
      for (const v of d.variants) {
        const body = v.fields.flatMap((f) => stripStmt(s, f, rustField(f.name), seen));
        o.line(`        ${k}::${pascal(v.kind)}${v.fields.length ? " { " + v.fields.map((f) => rustField(f.name)).join(", ") + " }" : ""} => { ${body.join(" ")} }`);
      }
      o.line("    }");
      for (const f of d.common) for (const l of stripStmt(s, f, `(&mut v.${rustField(f.name)})`, seen)) o.line("    " + l);
    }
    o.line("}");
    o.line();
  }
  const program = decl(s, "Program") as Decl & { d: "struct" };
  o.line("/// Resets every piece of type information to its default, leaving the");
  o.line("/// HIR that the same program without annotations produces.");
  o.line("pub fn strip(program: &mut Program) {");
  o.line("    let v = program;");
  for (const f of program.fields) for (const l of stripStmt(s, f, `(&mut v.${rustField(f.name)})`, new Set())) o.line("    " + l);
  o.line("}");
}
