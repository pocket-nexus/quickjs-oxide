function isDefault(s: Schema, t: TypeExpr, e: string): string {
  switch (t.t) {
    case "prim":
      if (t.name === "boolean") return `!*${e}`;
      if (t.name === "u32") return `*${e} == 0`;
      break;
    case "list":
      return `${e}.is_empty()`;
    case "nullable":
      return `${e}.is_none()`;
    case "named":
      if (decl(s, t.name).d === "ref") return `${e}.0 == 0`;
      break;
  }
  throw new Error(`no default for typed ${JSON.stringify(t)}`);
}

// An expression `String` for a simple value `e` of type `&T`.
function fmt(s: Schema, t: TypeExpr, e: string): string {
  switch (t.t) {
    case "prim":
      switch (t.name) {
        case "u32":
        case "i32":
          return `${e}.to_string()`;
        case "boolean":
          return `${e}.to_string()`;
        case "f64":
          return `fmt_f64(*${e})`;
        case "string":
          return `quote(${e})`;
      }
      break;
    case "list":
      return `format!("[{}]", ${e}.iter().map(|x| ${fmt(s, t.elem, "x")}).collect::<Vec<_>>().join(" "))`;
    case "nullable":
      return `${e}.as_ref().map_or_else(|| "null".to_string(), |x| ${fmt(s, t.inner, "x")})`;
    case "named": {
      const d = decl(s, t.name);
      if (d.name === "StringRef") return `d.string(*${e})`;
      if (d.name === "Span") return `format!("{}:{}-{}", ${e}.file.0, ${e}.start, ${e}.end)`;
      if (d.d === "ref") return `format!("#{}", ${e}.0)`;
      if (d.d === "enum") return `${e}.as_str().to_string()`;
      break;
    }
  }
  throw new Error(`not simple: ${JSON.stringify(t)}`);
}

// Statements dumping field `f` (value `e: &T`) into `parts` or as a child.
function dumpField(s: Schema, f: Field, e: string): string[] {
  const t = f.type;
  const isSpan = t.t === "named" && t.name === "Span";
  const guards: string[] = [];
  if (isSpan) guards.push("d.spans");
  if (f.typed) guards.push(`!(${isDefault(s, t, e)})`);
  const wrap = (body: string[]): string[] => (guards.length ? [`if ${guards.join(" && ")} {`, ...body.map((l) => "    " + l), "}"] : body);
  if (t.t === "nullable" && !simple(s, t)) {
    return wrap([`if let Some(x) = ${e} {`, `    children.push((${JSON.stringify(f.name)}, Child::One(Box::new(move |d: &mut Dumper<'_>, ind: usize| ${dumpCall(s, t.inner, "x")}))));`, "}"]);
  }
  if (t.t === "nullable") {
    return wrap([`if let Some(x) = ${e} {`, `    parts.push(format!("${f.name}:{}", ${fmt(s, t.inner, "x")}));`, "}"]);
  }
  if (simple(s, t)) {
    return wrap([`parts.push(format!("${f.name}:{}", ${fmt(s, t, e)}));`]);
  }
  if (t.t === "list") {
    return wrap([
      `if ${e}.is_empty() {`,
      `    parts.push("${f.name}:[]".to_string());`,
      "} else {",
      `    children.push((${JSON.stringify(f.name)}, Child::Many(${e}.iter().map(|x| -> Box<dyn Fn(&mut Dumper<'_>, usize) + '_> { Box::new(move |d: &mut Dumper<'_>, ind: usize| ${dumpCall(s, t.elem, "x")}) }).collect())));`,
      "}",
    ]);
  }
  return wrap([`children.push((${JSON.stringify(f.name)}, Child::One(Box::new(move |d: &mut Dumper<'_>, ind: usize| ${dumpCall(s, t, e)}))));`]);
}

function dumpCall(s: Schema, t: TypeExpr, e: string): string {
  if (t.t !== "named") throw new Error("complex dump of a non-named type");
  return `${fnName("d", t.name)}(d, ${e}, ind, String::new())`;
}

function dumpBody(s: Schema, fields: Field[], prefix: (f: Field) => string): string[] {
  const lines = ["let mut parts: Vec<String> = Vec::new();", "let mut children: Vec<(&str, Child<'_>)> = Vec::new();"];
  for (const f of fields) lines.push(...dumpField(s, f, prefix(f)));
  return lines;
}

function dumper(s: Schema, o: Out): void {
  o.line("// ---- dump ----");
  o.line();
  o.line("/// What [`dump_with`] prints besides the tree.");
  o.line("#[derive(Clone, Copy, Debug, Default)]");
  o.line("pub struct DumpOptions {");
  o.line("    /// Print every span as `file:start-end`.");
  o.line("    pub spans: bool,");
  o.line("}");
  o.line();
  o.line("struct Dumper<'a> {");
  o.line("    strings: &'a [JsString],");
  o.line("    spans: bool,");
  o.line("    out: String,");
  o.line("}");
  o.line();
  o.line("type Thunk<'a> = Box<dyn Fn(&mut Dumper<'_>, usize) + 'a>;");
  o.line();
  o.line("enum Child<'a> {");
  o.line("    One(Thunk<'a>),");
  o.line("    Many(Vec<Thunk<'a>>),");
  o.line("}");
  o.line();
  o.line("impl Dumper<'_> {");
  o.line("    fn string(&self, r: StringRef) -> String {");
  o.line("        self.strings.get(r.0 as usize).map_or_else(|| format!(\"#{}?\", r.0), quote)");
  o.line("    }");
  o.line();
  o.line("    // One record: its head and simple fields on a line, each complex field");
  o.line("    // on the next lines, its value two columns further in.");
  o.line("    fn record(&mut self, ind: usize, head: String, parts: Vec<String>, children: Vec<(&str, Child<'_>)>) {");
  o.line("        self.out.push_str(&\" \".repeat(ind));");
  o.line("        self.out.push_str(&head);");
  o.line("        for part in parts {");
  o.line("            self.out.push(' ');");
  o.line("            self.out.push_str(&part);");
  o.line("        }");
  o.line("        self.out.push('\\n');");
  o.line("        for (name, child) in children {");
  o.line("            self.out.push_str(&\" \".repeat(ind + 2));");
  o.line("            self.out.push_str(name);");
  o.line("            self.out.push_str(\":\\n\");");
  o.line("            match child {");
  o.line("                Child::One(f) => f(self, ind + 4),");
  o.line("                Child::Many(fs) => {");
  o.line("                    for f in fs {");
  o.line("                        f(self, ind + 4);");
  o.line("                    }");
  o.line("                }");
  o.line("            }");
  o.line("        }");
  o.line("    }");
  o.line("}");
  o.line();
  o.line("/// `JSON.stringify` of a string: lone surrogates and C0 controls escaped.");
  o.line("fn quote(s: &JsString) -> String {");
  o.line("    let mut out = String::from(\"\\\"\");");
  o.line("    for c in char::decode_utf16(s.utf16_units()) {");
  o.line("        match c {");
  o.line("            Ok('\"') => out.push_str(\"\\\\\\\"\"),");
  o.line("            Ok('\\\\') => out.push_str(\"\\\\\\\\\"),");
  o.line("            Ok('\\u{8}') => out.push_str(\"\\\\b\"),");
  o.line("            Ok('\\u{c}') => out.push_str(\"\\\\f\"),");
  o.line("            Ok('\\n') => out.push_str(\"\\\\n\"),");
  o.line("            Ok('\\r') => out.push_str(\"\\\\r\"),");
  o.line("            Ok('\\t') => out.push_str(\"\\\\t\"),");
  o.line("            Ok(c) if u32::from(c) < 0x20 => out.push_str(&format!(\"\\\\u{:04x}\", u32::from(c))),");
  o.line("            Ok(c) => out.push(c),");
  o.line("            Err(e) => out.push_str(&format!(\"\\\\u{:04x}\", e.unpaired_surrogate())),");
  o.line("        }");
  o.line("    }");
  o.line("    out.push('\"');");
  o.line("    out");
  o.line("}");
  o.line();
  o.line("/// An integer below 2^53 in decimal, else the shortest exponent form.");
  o.line("fn fmt_f64(x: f64) -> String {");
  o.line("    if x.is_nan() {");
  o.line("        \"NaN\".to_string()");
  o.line("    } else if x.is_infinite() {");
  o.line("        if x > 0.0 { \"Infinity\" } else { \"-Infinity\" }.to_string()");
  o.line("    } else if x == 0.0 && x.is_sign_negative() {");
  o.line("        \"-0\".to_string()");
  o.line("    } else if x.fract() == 0.0 && x.abs() <= 9_007_199_254_740_992.0 {");
  o.line("        #[allow(clippy::cast_possible_truncation)]");
  o.line("        let n = x as i64;");
  o.line("        n.to_string()");
  o.line("    } else {");
  o.line("        format!(\"{x:e}\")");
  o.line("    }");
  o.line("}");
  o.line();
  for (const name of s.order) {
    const d = decl(s, name);
    if (d.d === "struct" && name !== "Program") {
      o.line(`fn ${fnName("d", name)}(d: &mut Dumper<'_>, v: &${name}, ind: usize, head: String) {`);
      for (const l of dumpBody(s, d.fields, (f) => `(&v.${rustField(f.name)})`)) o.line("    " + l);
      o.line(`    d.record(ind, if head.is_empty() { ${JSON.stringify(name)}.to_string() } else { head }, parts, children);`);
      o.line("}");
      o.line();
    } else if (d.d === "union") {
      const k = kindEnum(d);
      const common = d.common;
      o.line(`fn ${fnName("d", name)}(d: &mut Dumper<'_>, v: &${name}, ind: usize, head: String) {`);
      o.line("    let mut parts: Vec<String> = Vec::new();");
      o.line("    let mut children: Vec<(&str, Child<'_>)> = Vec::new();");
      o.line(`    let kind = match ${common.length ? "&v.kind" : "v"} {`);
      for (const v of d.variants) {
        o.line(`        ${k}::${pascal(v.kind)}${bindings(v)} => {`);
        for (const f of v.fields) for (const l of dumpField(s, f, rustField(f.name))) o.line("            " + l);
        o.line(`            ${JSON.stringify(v.kind)}`);
        o.line("        }");
      }
      o.line("    };");
      for (const f of common) for (const l of dumpField(s, f, `(&v.${rustField(f.name)})`)) o.line("    " + l);
      o.line("    let head = if head.is_empty() { kind.to_string() } else { format!(\"{head} {kind}\") };");
      o.line("    d.record(ind, head, parts, children);");
      o.line("}");
      o.line();
    }
  }

  const program = decl(s, "Program") as Decl & { d: "struct" };
  o.line("/// The text form of `program`, without spans.");
  o.line("#[must_use]");
  o.line("pub fn dump(program: &Program) -> String {");
  o.line("    dump_with(program, DumpOptions::default())");
  o.line("}");
  o.line();
  o.line("/// The text form of `program`.");
  o.line("#[must_use]");
  o.line("pub fn dump_with(program: &Program, options: DumpOptions) -> String {");
  o.line("    let v = program;");
  o.line("    let mut d = Dumper { strings: &program.strings, spans: options.spans, out: String::new() };");
  o.line("    {");
  o.line("        let d = &mut d;");
  for (const l of dumpBody(s, program.fields.filter((f) => !tableField(f)), (f) => `(&v.${rustField(f.name)})`)) o.line("        " + l);
  o.line("        d.record(0, \"program\".to_string(), parts, children);");
  o.line("    }");
  for (const f of program.fields) {
    const tag = tableField(f);
    if (!tag || f.type.t !== "list") continue;
    const head = TABLE_HEADS[f.name];
    o.line(`    for (i, x) in v.${rustField(f.name)}.iter().enumerate() {`);
    const elem = f.type.elem;
    if (simple(s, elem)) {
      o.line(`        d.record(0, format!("${head} #{i}"), vec![${fmt(s, elem, "x")}], Vec::new());`);
    } else {
      o.line(`        ${fnName("d", (elem as { name: string }).name)}(&mut d, x, 0, format!("${head} #{i}"));`);
    }
    o.line("    }");
  }
  o.line("    d.out");
  o.line("}");
  o.line();
}

