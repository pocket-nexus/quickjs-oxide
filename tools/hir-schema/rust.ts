// Emits `src/engine/hir/schema.rs`: the Rust types, writer, reader, dump and
// strip for the schema.

import {
  type Decl,
  type Field,
  type Schema,
  type TypeExpr,
  decl,
  hasNodeSpan,
  isNode,
  pascal,
  simple,
  snake,
  variantFields,
  words,
} from "./schema.ts";
import { TABLES, tableField } from "./tables.ts";

const KEYWORDS = new Set([
  "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
  "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
  "ref", "return", "self", "static", "struct", "super", "trait", "true", "type", "unsafe", "use",
  "where", "while", "yield", "abstract", "become", "box", "do", "final", "macro", "override",
  "priv", "try", "typeof", "unsized", "virtual", "gen",
]);

export function rustField(name: string): string {
  const s = snake(name);
  return KEYWORDS.has(s) ? `${s}_` : s;
}

function fnName(prefix: string, type: string): string {
  return `${prefix}_${snake(type).replace(/^_/, "")}`;
}

class Out {
  lines: string[] = [];
  line(s = ""): void {
    this.lines.push(s);
  }
  text(): string {
    return this.lines.join("\n") + "\n";
  }
}

export function emitRust(s: Schema, version: number): string {
  const o = new Out();
  o.line("// @generated by tools/hir-schema/gen.ts from contracts/spec/hir.ts; do not edit.");
  o.line("//! The HIR schema: types, the binary reader and writer, the text dump and");
  o.line("//! `strip`, all generated from `contracts/spec/hir.ts`, whose header");
  o.line("//! describes the encoding.");
  o.line("#![allow(clippy::all, unused_variables, unused_parens, unused_mut)]");
  o.line();
  o.line("use crate::engine::value::JsString;");
  o.line();
  o.line(`pub const SCHEMA_VERSION: u32 = ${version};`);
  o.line();
  types(s, o);
  writer(s, o);
  reader(s, o);
  dumper(s, o);
  stripper(s, o);
  return o.text();
}

// ---- types ----

// Fields the Rust types box so the enums holding them stay small: the class
// a class expression or declaration carries, a tagged template's string
// lists and a try statement's blocks. The encoding does not change.
function boxed(s: Schema, f: Field, variant?: string): boolean {
  const t = f.type.t === "nullable" ? f.type.inner : f.type;
  if (t.t === "named" && t.name === "Block") return variant === "try";
  if (t.t === "named") return t.name === "Class" && decl(s, t.name).d === "struct";
  return t.t === "list" && (f.name === "cooked" || f.name === "raw");
}

function fieldTy(s: Schema, f: Field, variant?: string): string {
  if (!boxed(s, f, variant)) return rty(s, f.type);
  if (f.type.t === "nullable") return `Option<Box<${rty(s, f.type.inner)}>>`;
  return `Box<${rty(s, f.type)}>`;
}

function fieldDec(s: Schema, f: Field, variant?: string): string {
  const e = dec(s, f.type);
  if (!boxed(s, f, variant)) return e;
  if (f.type.t === "nullable") return `(${e}).map(Box::new)`;
  return `Box::new(${e})`;
}

function rty(s: Schema, t: TypeExpr, inList = false): string {
  switch (t.t) {
    case "prim":
      return { u32: "u32", i32: "i32", f64: "f64", boolean: "bool", string: "JsString" }[t.name];
    case "list":
      return `Vec<${rty(s, t.elem, true)}>`;
    case "nullable":
      return `Option<${rty(s, t.inner)}>`;
    case "named":
      return isNode(s, t) && !inList ? `Box<${t.name}>` : t.name;
  }
}

function kindEnum(d: Decl & { d: "union" }): string {
  return d.common.length > 0 ? `${d.name}Kind` : d.name;
}

function types(s: Schema, o: Out): void {
  for (const name of s.order) {
    const d = decl(s, name);
    if (name === "Program") o.line("/// One compilation unit: every module and the tables they share.");
    switch (d.d) {
      case "ref":
        o.line("#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]");
        o.line(`pub struct ${name}(pub u32);`);
        o.line();
        o.line(`impl ${name} {`);
        o.line("    #[must_use]");
        if (name === "TypeRef") {
          o.line("    pub const fn index(self) -> Option<usize> {");
          o.line("        (self.0 as usize).checked_sub(1)");
        } else {
          o.line("    pub const fn index(self) -> usize {");
          o.line("        self.0 as usize");
        }
        o.line("    }");
        o.line("}");
        break;
      case "enum":
        o.line("#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]");
        o.line(`pub enum ${name} {`);
        for (const n of d.names) o.line(`    ${n},`);
        o.line("}");
        o.line();
        o.line(`impl ${name} {`);
        o.line(`    pub const ALL: &'static [${name}] = &[${d.names.map((n) => `${name}::${n}`).join(", ")}];`);
        o.line();
        o.line("    #[must_use]");
        o.line("    pub const fn as_str(self) -> &'static str {");
        o.line("        match self {");
        d.names.forEach((n, i) => o.line(`            ${name}::${n} => ${JSON.stringify(d.members[i])},`));
        o.line("        }");
        o.line("    }");
        o.line("}");
        break;
      case "struct":
        o.line("#[derive(Clone, Debug, PartialEq)]");
        o.line(`pub struct ${name} {`);
        for (const f of d.fields) o.line(`    pub ${rustField(f.name)}: ${fieldTy(s, f)},`);
        o.line("}");
        break;
      case "union": {
        const k = kindEnum(d);
        if (d.common.length > 0) {
          o.line("#[derive(Clone, Debug, PartialEq)]");
          o.line(`pub struct ${name} {`);
          o.line(`    pub kind: ${k},`);
          for (const f of d.common) o.line(`    pub ${rustField(f.name)}: ${fieldTy(s, f)},`);
          o.line("}");
          o.line();
        }
        o.line("#[derive(Clone, Debug, PartialEq)]");
        o.line(`pub enum ${k} {`);
        for (const v of d.variants) {
          if (v.fields.length === 0) {
            o.line(`    ${pascal(v.kind)},`);
          } else {
            o.line(`    ${pascal(v.kind)} {`);
            for (const f of v.fields) o.line(`        ${rustField(f.name)}: ${fieldTy(s, f, v.kind)},`);
            o.line("    },");
          }
        }
        o.line("}");
        o.line();
        o.line(`impl ${k} {`);
        o.line("    #[must_use]");
        o.line("    pub const fn kind_name(&self) -> &'static str {");
        o.line("        match self {");
        for (const v of d.variants) o.line(`            ${k}::${pascal(v.kind)}${v.fields.length ? " { .. }" : ""} => ${JSON.stringify(v.kind)},`);
        o.line("        }");
        o.line("    }");
        o.line("}");
        break;
      }
    }
    o.line();
  }
}

function bindings(v: { fields: Field[] }): string {
  return v.fields.length === 0 ? "" : ` { ${v.fields.map((f) => rustField(f.name)).join(", ")} }`;
}

// ---- writer ----

let tmp = 0;

// Appends the words of `e` (an expression of type `&T`) to `out`.
function enc(s: Schema, t: TypeExpr, e: string, out: string): string {
  switch (t.t) {
    case "prim":
      switch (t.name) {
        case "u32":
          return `${out}.push(*${e});`;
        case "i32":
          return `${out}.push(*${e} as u32);`;
        case "boolean":
          return `${out}.push(u32::from(*${e}));`;
        case "f64":
          return `push_f64(${out}, *${e});`;
        case "string":
          return `w.string(${out}, ${e});`;
      }
      break;
    case "list": {
      const b = `buf${tmp++}`;
      const x = `x${tmp++}`;
      return `{ let ${b} = &mut Vec::new(); for ${x} in ${e}.iter() { ${enc(s, t.elem, x, b)} } w.list(${out}, std::mem::take(${b}), ${e}.len()); }`;
    }
    case "nullable": {
      const x = `x${tmp++}`;
      const inner = t.inner;
      const n = words(s, t);
      if (inner.t === "prim" && inner.name === "f64") {
        return `match ${e} { Some(${x}) => { ${out}.push(1); push_f64(${out}, *${x}); } None => ${out}.extend([0; 3]), }`;
      }
      if (inner.t === "named" && decl(s, inner.name).d === "struct") {
        return `match ${e} { Some(${x}) => { ${out}.push(1); ${enc(s, inner, x, out)} } None => ${out}.extend([0; ${n}]), }`;
      }
      if (isNode(s, inner)) {
        return `match ${e} { Some(${x}) => { let r = ${fnName("n", inner.name)}(w, ${x}); ${out}.push(r); } None => ${out}.push(0), }`;
      }
      return `match ${e} { Some(${x}) => ${out}.push(${scalarWord(s, inner, x)} + 1), None => ${out}.push(0), }`;
    }
    case "named": {
      const d = decl(s, t.name);
      if (d.d === "ref" || d.d === "enum") return `${out}.push(${scalarWord(s, t, e)});`;
      if (d.d === "struct") return `${fnName("w", t.name)}(w, ${out}, ${e});`;
      if (s.inline.has(t.name)) return `${fnName("w", t.name)}(w, ${out}, ${e});`;
      return `{ let r = ${fnName("n", t.name)}(w, ${e}); ${out}.push(r); }`;
    }
  }
  throw new Error("unreachable");
}

function scalarWord(s: Schema, t: TypeExpr, e: string): string {
  if (t.t === "prim") {
    if (t.name === "u32") return `*${e}`;
    if (t.name === "i32") return `(*${e} as u32)`;
    if (t.name === "boolean") return `u32::from(*${e})`;
  }
  if (t.t === "named") {
    const d = decl(s, t.name);
    if (d.d === "ref") return `${e}.0`;
    if (d.d === "enum") return `(*${e} as u32)`;
  }
  throw new Error(`no scalar word for ${JSON.stringify(t)}`);
}

function writer(s: Schema, o: Out): void {
  o.line("// ---- writer ----");
  o.line();
  o.line("#[derive(Default)]");
  o.line("struct Writer {");
  o.line("    nodes: Vec<u32>,");
  o.line("    spans: Vec<u32>,");
  o.line("    lists: Vec<u32>,");
  o.line("    count: u32,");
  o.line("}");
  o.line();
  o.line("impl Writer {");
  o.line("    fn node(&mut self, words: Vec<u32>, span: Option<&Span>) -> u32 {");
  o.line("        self.nodes.extend(words);");
  o.line("        match span {");
  o.line("            Some(span) => self.spans.extend([span.file.0, span.start, span.end]),");
  o.line("            None => self.spans.extend([0; 3]),");
  o.line("        }");
  o.line("        self.count += 1;");
  o.line("        self.count");
  o.line("    }");
  o.line();
  o.line("    fn list(&mut self, out: &mut Vec<u32>, items: Vec<u32>, len: usize) {");
  o.line("        out.push(word(self.lists.len()));");
  o.line("        out.push(word(len));");
  o.line("        self.lists.extend(items);");
  o.line("    }");
  o.line();
  o.line("    fn string(&mut self, out: &mut Vec<u32>, value: &JsString) {");
  o.line("        out.push(word(self.lists.len()));");
  o.line("        out.push(word(value.len()));");
  o.line("        let mut units = value.utf16_units();");
  o.line("        while let Some(low) = units.next() {");
  o.line("            let high = units.next().unwrap_or(0);");
  o.line("            self.lists.push(u32::from(low) | u32::from(high) << 16);");
  o.line("        }");
  o.line("    }");
  o.line("}");
  o.line();
  o.line("fn word(n: usize) -> u32 {");
  o.line("    u32::try_from(n).expect(\"HIR tables are indexed by u32\")");
  o.line("}");
  o.line();
  o.line("fn push_f64(out: &mut Vec<u32>, value: f64) {");
  o.line("    let bits = value.to_bits();");
  o.line("    out.push(bits as u32);");
  o.line("    out.push((bits >> 32) as u32);");
  o.line("}");
  o.line();
  for (const name of s.order) {
    const d = decl(s, name);
    if (d.d === "struct" && name !== "Program") {
      o.line(`fn ${fnName("w", name)}(w: &mut Writer, out: &mut Vec<u32>, v: &${name}) {`);
      for (const f of d.fields) o.line(`    ${enc(s, f.type, `(&v.${rustField(f.name)})`, "out")}`);
      o.line("}");
      o.line();
    } else if (d.d === "union" && s.inline.has(name)) {
      o.line(`fn ${fnName("w", name)}(w: &mut Writer, out: &mut Vec<u32>, v: &${name}) {`);
      o.line("    match v {");
      d.variants.forEach((v, i) => {
        o.line(`        ${name}::${pascal(v.kind)}${bindings(v)} => {`);
        o.line(`            out.push(${i});`);
        for (const f of v.fields) o.line(`            ${enc(s, f.type, rustField(f.name), "out")}`);
        o.line("        }");
      });
      o.line("    }");
      o.line("}");
      o.line();
    } else if (d.d === "union") {
      const k = kindEnum(d);
      const common = variantFields(s, d, { kind: "", fields: [] });
      o.line(`fn ${fnName("n", name)}(w: &mut Writer, v: &${name}) -> u32 {`);
      o.line("    let mut words = Vec::new();");
      o.line("    let out = &mut words;");
      o.line(`    match ${d.common.length ? "&v.kind" : "v"} {`);
      d.variants.forEach((v, i) => {
        o.line(`        ${k}::${pascal(v.kind)}${bindings(v)} => {`);
        o.line(`            out.push(${d.kinds! + i});`);
        for (const f of v.fields) o.line(`            ${enc(s, f.type, rustField(f.name), "out")}`);
        o.line("        }");
      });
      o.line("    }");
      for (const f of common) o.line(`    ${enc(s, f.type, `(&v.${rustField(f.name)})`, "out")}`);
      o.line(`    w.node(words, ${hasNodeSpan(s, d) ? "Some(&v.span)" : "None"})`);
      o.line("}");
      o.line();
    }
  }

  const program = decl(s, "Program") as Decl & { d: "struct" };
  o.line("/// The binary form of `program`.");
  o.line("#[must_use]");
  o.line("pub fn write(program: &Program) -> Vec<u8> {");
  o.line("    let v = program;");
  o.line("    let mut writer = Writer::default();");
  o.line("    let w = &mut writer;");
  o.line("    let mut head_words = Vec::new();");
  o.line("    let head = &mut head_words;");
  for (const f of program.fields) if (!tableField(f)) o.line(`    ${enc(s, f.type, `(&v.${rustField(f.name)})`, "head")}`);
  o.line("    let mut sections: Vec<(u16, Vec<u32>)> = Vec::new();");
  for (const f of program.fields) {
    const tag = tableField(f);
    if (!tag || f.type.t !== "list") continue;
    o.line("    {");
    o.line("        let mut words = vec![word(v." + rustField(f.name) + ".len())];");
    o.line("        let out = &mut words;");
    o.line(`        for x in &v.${rustField(f.name)} { ${enc(s, f.type.elem, "x", "out")} }`);
    o.line(`        sections.push((${tag}, words));`);
    o.line("    }");
  }
  o.line(`    sections.push((${TABLES.nodes}, std::mem::take(&mut w.nodes)));`);
  o.line(`    sections.push((${TABLES.spans}, std::mem::take(&mut w.spans)));`);
  o.line(`    sections.push((${TABLES.lists}, std::mem::take(&mut w.lists)));`);
  o.line(`    sections.push((${TABLES.program}, head_words));`);
  o.line("    sections.sort_by_key(|(tag, _)| *tag);");
  o.line("    let mut bytes = Vec::new();");
  o.line("    bytes.extend_from_slice(b\"HIR1\");");
  o.line("    bytes.extend_from_slice(&SCHEMA_VERSION.to_le_bytes());");
  o.line("    bytes.extend_from_slice(&word(sections.len()).to_le_bytes());");
  o.line("    bytes.extend_from_slice(&fingerprint(&program.unit.fingerprint_inputs).to_le_bytes());");
  o.line("    for (tag, words) in sections {");
  o.line("        bytes.extend_from_slice(&tag.to_le_bytes());");
  o.line("        bytes.extend_from_slice(&0u16.to_le_bytes());");
  o.line("        bytes.extend_from_slice(&word(words.len() * 4).to_le_bytes());");
  o.line("        bytes.extend_from_slice(&[0; 8]);");
  o.line("        for x in words {");
  o.line("            bytes.extend_from_slice(&x.to_le_bytes());");
  o.line("        }");
  o.line("        while bytes.len() % 16 != 0 {");
  o.line("            bytes.push(0);");
  o.line("        }");
  o.line("    }");
  o.line("    bytes");
  o.line("}");
  o.line();
  o.line("/// FNV-1a over the UTF-16LE bytes of each input, each followed by two zero bytes.");
  o.line("#[must_use]");
  o.line("pub fn fingerprint(inputs: &[JsString]) -> u32 {");
  o.line("    let mut hash: u32 = 0x811c_9dc5;");
  o.line("    let mut byte = |b: u8| {");
  o.line("        hash ^= u32::from(b);");
  o.line("        hash = hash.wrapping_mul(0x0100_0193);");
  o.line("    };");
  o.line("    for input in inputs {");
  o.line("        for unit in input.utf16_units() {");
  o.line("            let [low, high] = unit.to_le_bytes();");
  o.line("            byte(low);");
  o.line("            byte(high);");
  o.line("        }");
  o.line("        byte(0);");
  o.line("        byte(0);");
  o.line("    }");
  o.line("    hash");
  o.line("}");
  o.line();
}

// ---- reader ----

// An expression decoding a `T` from cursor `c` (child node refs below `limit`).
function dec(s: Schema, t: TypeExpr, inList = false): string {
  switch (t.t) {
    case "prim":
      switch (t.name) {
        case "u32":
          return "c.u()?";
        case "i32":
          return "(c.u()? as i32)";
        case "boolean":
          return "c.flag()?";
        case "f64":
          return "c.f64()?";
        case "string":
          return "r.string(c)?";
      }
      break;
    case "list": {
      const x = `l${tmp++}`;
      return `{ let (mut ${x}, n) = r.list(c, ${words(s, t.elem)})?; let mut v = Vec::with_capacity(n); for _ in 0..n { let c = &mut ${x}; v.push(${dec(s, t.elem, true)}); } v }`;
    }
    case "nullable": {
      const inner = t.inner;
      if (inner.t === "prim" && inner.name === "f64") {
        return "{ let present = c.flag()?; let x = c.f64()?; present.then_some(x) }";
      }
      if (inner.t === "named" && decl(s, inner.name).d === "struct") {
        return `{ let present = c.flag()?; let x = ${dec(s, inner)}; present.then_some(x) }`;
      }
      if (isNode(s, inner)) {
        return `match c.u()? { 0 => None, n => Some(Box::new(${fnName("rn", inner.name)}(r, n, limit)?)) }`;
      }
      return `match c.u()? { 0 => None, n => Some(${scalarFrom(s, inner, "(n - 1)")}) }`;
    }
    case "named": {
      const d = decl(s, t.name);
      if (d.d === "ref" || d.d === "enum") return scalarFrom(s, t, "c.u()?");
      if (d.d === "struct") return `${fnName("r", t.name)}(r, c, limit)?`;
      if (s.inline.has(t.name)) return `${fnName("r", t.name)}(r, c, limit)?`;
      return inList ? `${fnName("rn", t.name)}(r, c.u()?, limit)?` : `Box::new(${fnName("rn", t.name)}(r, c.u()?, limit)?)`;
    }
  }
  throw new Error("unreachable");
}

function scalarFrom(s: Schema, t: TypeExpr, w: string): string {
  if (t.t === "prim") {
    if (t.name === "u32") return w;
    if (t.name === "i32") return `(${w} as i32)`;
    if (t.name === "boolean") return `(${w} != 0)`;
  }
  if (t.t === "named") {
    const d = decl(s, t.name);
    if (d.d === "ref") return `${t.name}(${w})`;
    if (d.d === "enum") return `enum_at(${t.name}::ALL, ${w})?`;
  }
  throw new Error(`no scalar for ${JSON.stringify(t)}`);
}

function reader(s: Schema, o: Out): void {
  o.line("// ---- reader ----");
  o.line();
  o.line("/// Why a byte string is not a HIR file this reader can use.");
  o.line("#[derive(Clone, Debug, PartialEq, Eq)]");
  o.line("pub struct ReadError(pub &'static str);");
  o.line();
  o.line("impl std::fmt::Display for ReadError {");
  o.line("    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {");
  o.line("        write!(f, \"malformed HIR: {}\", self.0)");
  o.line("    }");
  o.line("}");
  o.line();
  o.line("impl std::error::Error for ReadError {}");
  o.line();
  o.line("struct Cur<'a> {");
  o.line("    words: &'a [u32],");
  o.line("    at: usize,");
  o.line("}");
  o.line();
  o.line("impl Cur<'_> {");
  o.line("    fn u(&mut self) -> Result<u32, ReadError> {");
  o.line("        let x = *self.words.get(self.at).ok_or(ReadError(\"truncated record\"))?;");
  o.line("        self.at += 1;");
  o.line("        Ok(x)");
  o.line("    }");
  o.line();
  o.line("    fn flag(&mut self) -> Result<bool, ReadError> {");
  o.line("        match self.u()? {");
  o.line("            0 => Ok(false),");
  o.line("            1 => Ok(true),");
  o.line("            _ => Err(ReadError(\"a boolean is neither 0 nor 1\")),");
  o.line("        }");
  o.line("    }");
  o.line();
  o.line("    fn f64(&mut self) -> Result<f64, ReadError> {");
  o.line("        let low = u64::from(self.u()?);");
  o.line("        let high = u64::from(self.u()?);");
  o.line("        Ok(f64::from_bits(low | high << 32))");
  o.line("    }");
  o.line("}");
  o.line();
  o.line("fn enum_at<T: Copy>(all: &[T], n: u32) -> Result<T, ReadError> {");
  o.line("    all.get(n as usize).copied().ok_or(ReadError(\"an enumeration value is out of range\"))");
  o.line("}");
  o.line();
  o.line("struct Reader<'a> {");
  o.line("    nodes: &'a [u32],");
  o.line("    offsets: Vec<usize>,");
  o.line("    spans: &'a [u32],");
  o.line("    lists: &'a [u32],");
  o.line("}");
  o.line();
  o.line("impl<'a> Reader<'a> {");
  o.line("    fn list(&self, c: &mut Cur<'_>, size: usize) -> Result<(Cur<'a>, usize), ReadError> {");
  o.line("        let start = c.u()? as usize;");
  o.line("        let len = c.u()? as usize;");
  o.line("        let end = len.checked_mul(size).and_then(|n| n.checked_add(start));");
  o.line("        if end.is_none_or(|end| end > self.lists.len()) {");
  o.line("            return Err(ReadError(\"a list runs past the list section\"));");
  o.line("        }");
  o.line("        Ok((Cur { words: self.lists, at: start }, len))");
  o.line("    }");
  o.line();
  o.line("    fn string(&self, c: &mut Cur<'_>) -> Result<JsString, ReadError> {");
  o.line("        let start = c.u()? as usize;");
  o.line("        let len = c.u()? as usize;");
  o.line("        if len > JsString::MAX_LEN {");
  o.line("            return Err(ReadError(\"a string is too long\"));");
  o.line("        }");
  o.line("        let words = self");
  o.line("            .lists");
  o.line("            .get(start..start + len.div_ceil(2))");
  o.line("            .ok_or(ReadError(\"a string runs past the list section\"))?;");
  o.line("        let units = words");
  o.line("            .iter()");
  o.line("            .flat_map(|w| [*w as u16, (*w >> 16) as u16])");
  o.line("            .take(len)");
  o.line("            .collect();");
  o.line("        Ok(JsString::from_owned_utf16(units))");
  o.line("    }");
  o.line();
  o.line("    // Node `n` (index plus 1) as a cursor after its kind word. A child is");
  o.line("    // written before its parent, so its index is below `limit`.");
  o.line("    fn node(&self, n: u32, limit: usize) -> Result<(usize, u32, Cur<'a>), ReadError> {");
  o.line("        let index = (n as usize).checked_sub(1).ok_or(ReadError(\"a node reference is 0\"))?;");
  o.line("        if index >= limit {");
  o.line("            return Err(ReadError(\"a node reference does not point to an earlier node\"));");
  o.line("        }");
  o.line("        let at = self.offsets[index];");
  o.line("        Ok((index, self.nodes[at], Cur { words: self.nodes, at: at + 1 }))");
  o.line("    }");
  o.line();
  o.line("    fn span(&self, index: usize) -> Span {");
  o.line("        match self.spans.get(index * 3..index * 3 + 3) {");
  o.line("            Some(&[file, start, end]) => Span { file: FileRef(file), start, end },");
  o.line("            _ => Span { file: FileRef(0), start: 0, end: 0 },");
  o.line("        }");
  o.line("    }");
  o.line("}");
  o.line();
  o.line("/// The size in words of a node of kind `kind`, its kind word included.");
  o.line("#[must_use]");
  o.line("pub const fn node_words(kind: u32) -> Option<usize> {");
  o.line("    match kind {");
  for (const name of s.order) {
    const d = decl(s, name);
    if (d.d !== "union" || s.inline.has(name)) continue;
    d.variants.forEach((v, i) => {
      const n = 1 + variantFields(s, d, v).reduce((a, f) => a + words(s, f.type), 0);
      o.line(`        ${d.kinds! + i} => Some(${n}),`);
    });
  }
  o.line("        _ => None,");
  o.line("    }");
  o.line("}");
  o.line();
  for (const name of s.order) {
    const d = decl(s, name);
    if (d.d === "struct" && name !== "Program") {
      o.line(`fn ${fnName("r", name)}(r: &Reader<'_>, c: &mut Cur<'_>, limit: usize) -> Result<${name}, ReadError> {`);
      for (const f of d.fields) o.line(`    let ${rustField(f.name)} = ${fieldDec(s, f)};`);
      o.line(`    Ok(${name} { ${d.fields.map((f) => rustField(f.name)).join(", ")} })`);
      o.line("}");
      o.line();
    } else if (d.d === "union" && s.inline.has(name)) {
      o.line(`fn ${fnName("r", name)}(r: &Reader<'_>, c: &mut Cur<'_>, limit: usize) -> Result<${name}, ReadError> {`);
      o.line("    Ok(match c.u()? {");
      d.variants.forEach((v, i) => {
        o.line(`        ${i} => {`);
        for (const f of v.fields) o.line(`            let ${rustField(f.name)} = ${fieldDec(s, f, v.kind)};`);
        o.line(`            ${name}::${pascal(v.kind)}${bindings(v)}`);
        o.line("        }");
      });
      o.line(`        _ => return Err(ReadError("unknown ${name} kind")),`);
      o.line("    })");
      o.line("}");
      o.line();
    } else if (d.d === "union") {
      const k = kindEnum(d);
      const common = variantFields(s, d, { kind: "", fields: [] });
      o.line(`fn ${fnName("rn", name)}(r: &Reader<'_>, n: u32, limit: usize) -> Result<${name}, ReadError> {`);
      o.line("    let (index, kind, mut cur) = r.node(n, limit)?;");
      o.line("    let (c, limit) = (&mut cur, index);");
      o.line("    let value = match kind {");
      d.variants.forEach((v, i) => {
        o.line(`        ${d.kinds! + i} => {`);
        for (const f of v.fields) o.line(`            let ${rustField(f.name)} = ${fieldDec(s, f, v.kind)};`);
        o.line(`            ${k}::${pascal(v.kind)}${bindings(v)}`);
        o.line("        }");
      });
      o.line(`        _ => return Err(ReadError("a node is not a ${name}")),`);
      o.line("    };");
      if (d.common.length === 0) {
        o.line("    Ok(value)");
      } else {
        for (const f of common) o.line(`    let ${rustField(f.name)} = ${fieldDec(s, f)};`);
        const fields = d.common.map((f) => (f.name === "span" && hasNodeSpan(s, d) ? "span: r.span(index)" : rustField(f.name)));
        o.line(`    Ok(${name} { kind: value, ${fields.join(", ")} })`);
      }
      o.line("}");
      o.line();
    }
  }

  const program = decl(s, "Program") as Decl & { d: "struct" };
  o.line("/// Reads a HIR file written by [`write`] or the TypeScript writer.");
  o.line("///");
  o.line("/// # Errors");
  o.line("/// Returns why `bytes` is not a well-formed HIR file of this schema version.");
  o.line("pub fn read(bytes: &[u8]) -> Result<Program, ReadError> {");
  o.line("    let header = |at: usize| -> Result<u32, ReadError> {");
  o.line("        let b = bytes.get(at..at + 4).ok_or(ReadError(\"truncated header\"))?;");
  o.line("        Ok(u32::from_le_bytes([b[0], b[1], b[2], b[3]]))");
  o.line("    };");
  o.line("    if bytes.get(..4) != Some(b\"HIR1\") {");
  o.line("        return Err(ReadError(\"no HIR1 magic\"));");
  o.line("    }");
  o.line("    if header(4)? != SCHEMA_VERSION {");
  o.line("        return Err(ReadError(\"another schema version\"));");
  o.line("    }");
  o.line("    let count = header(8)?;");
  o.line("    let mut sections: Vec<(u16, Vec<u32>)> = Vec::new();");
  o.line("    let mut at = 16;");
  o.line("    for _ in 0..count {");
  o.line("        let head = bytes.get(at..at + 16).ok_or(ReadError(\"truncated section header\"))?;");
  o.line("        let tag = u16::from_le_bytes([head[0], head[1]]);");
  o.line("        let len = u32::from_le_bytes([head[4], head[5], head[6], head[7]]) as usize;");
  o.line("        if len % 4 != 0 {");
  o.line("            return Err(ReadError(\"a section is not whole words\"));");
  o.line("        }");
  o.line("        let payload = bytes");
  o.line("            .get(at + 16..at + 16 + len)");
  o.line("            .ok_or(ReadError(\"a section runs past the end\"))?;");
  o.line("        let words = payload");
  o.line("            .chunks_exact(4)");
  o.line("            .map(|b| u32::from_le_bytes([b[0], b[1], b[2], b[3]]))");
  o.line("            .collect();");
  o.line("        sections.push((tag, words));");
  o.line("        at += 16 + len.next_multiple_of(16);");
  o.line("    }");
  o.line("    let section = |tag: u16| sections.iter().find(|(t, _)| *t == tag).map(|(_, w)| w.as_slice());");
  o.line(`    let nodes = section(${TABLES.nodes}).unwrap_or(&[]);`);
  o.line("    let mut offsets = Vec::new();");
  o.line("    let mut i = 0;");
  o.line("    while i < nodes.len() {");
  o.line("        offsets.push(i);");
  o.line("        i += node_words(nodes[i]).ok_or(ReadError(\"unknown node kind\"))?;");
  o.line("    }");
  o.line("    if i != nodes.len() {");
  o.line("        return Err(ReadError(\"the last node is truncated\"));");
  o.line("    }");
  o.line("    let limit = offsets.len();");
  o.line("    let reader = Reader {");
  o.line("        nodes,");
  o.line("        offsets,");
  o.line(`        spans: section(${TABLES.spans}).unwrap_or(&[]),`);
  o.line(`        lists: section(${TABLES.lists}).unwrap_or(&[]),`);
  o.line("    };");
  o.line("    let r = &reader;");
  o.line(`    let mut head = Cur { words: section(${TABLES.program}).ok_or(ReadError("no program section"))?, at: 0 };`);
  o.line("    let c = &mut head;");
  for (const f of program.fields) if (!tableField(f)) o.line(`    let ${rustField(f.name)} = ${dec(s, f.type)};`);
  for (const f of program.fields) {
    const tag = tableField(f);
    if (!tag || f.type.t !== "list") continue;
    o.line(`    let ${rustField(f.name)} = match section(${tag}) {`);
    o.line("        None => Vec::new(),");
    o.line("        Some(words) => {");
    o.line("            let c = &mut Cur { words, at: 0 };");
    o.line("            let n = c.u()? as usize;");
    o.line("            let mut v = Vec::with_capacity(n.min(words.len()));");
    o.line(`            for _ in 0..n { v.push(${dec(s, f.type.elem, true)}); }`);
    o.line("            v");
    o.line("        }");
    o.line("    };");
  }
  o.line(`    Ok(Program { ${program.fields.map((f) => rustField(f.name)).join(", ")} })`);
  o.line("}");
  o.line();
}

